"""Bind an authored JS module to the packaged space renderer and an optional DOM overlay."""
import argparse
import json
import re
import shutil
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
MARK = "<!-- generated by code-film-render stage.py -->"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--module", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()
    module = a.module.resolve()
    page = a.out.resolve()
    if not module.is_file() or module.parent != page.parent:
        ap.error("module and output page must share a directory")
    if page.exists() and not page.read_text(encoding="utf8").startswith(MARK):
        ap.error("existing output was authored separately")
    engine = page.parent / ".codefilm-engine"
    kit = (ROOT / "kit_space.html").read_text(encoding="utf8")
    code = re.search(r'<script type="module">(.+?)</script>', kit, re.S).group(1)
    code = code.replace("  applyAnim(t);", "  applyAnim(t);\n  if (updateCustom) updateCustom(t);", 1)
    hook = "const updateCustom = window.decorateSpace?.({THREE,scene,root,camera,overlay:document.getElementById('overlay')});"
    code = code.replace("window.FILM =", hook + "\nwindow.FILM =", 1)
    for rel in ("vendor/three/build/three.module.js", "vendor/three/build/three.core.js",
                "vendor/three/RoundedBoxGeometry.js","vendor/three/LICENSE"):
        dest = engine / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        if not dest.exists() or dest.read_bytes() != (ROOT/rel).read_bytes():
            shutil.copyfile(ROOT/rel, dest)
    for helper in ("surfaces.mjs", "brush.mjs"):
        shutil.copyfile(ROOT/"tools"/helper, engine/helper)
    (engine/"space.mjs").write_text(code, encoding="utf8")
    body = kit[:kit.index('<script type="module">')].replace('./vendor/', './.codefilm-engine/vendor/')
    body += '<div id="overlay" style="position:absolute;inset:0;pointer-events:none"></div>'
    url = json.dumps("./" + quote(module.name))
    body += f'<script type="module">import * as shot from {url};\n'
    body += """window.SPACE_SPEC = shot.spec;
window.SPACE_RENDER_SIZE = [Math.round(innerWidth * devicePixelRatio), Math.round(innerHeight * devicePixelRatio)];
window.decorateSpace = shot.setup;
await import('./.codefilm-engine/space.mjs');
</script></body></html>"""
    page.write_text(MARK + "\n" + body, encoding="utf8")
    print(page.name, "|", module.name)


if __name__ == "__main__":
    main()
